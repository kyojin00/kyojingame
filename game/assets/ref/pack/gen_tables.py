def fmt(row):
    return "[" + ", ".join("[%d, %d, %d]" % tuple(c) for c in row) + "]"


def emit(name, comment, rows):
    print("# " + comment)
    print("const %s := [" % name)
    for lbl, row in rows:
        print("\t%s,  # %s" % (fmt(row), lbl))
    print("]")


