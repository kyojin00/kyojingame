"""팩 팔레트에 맞춘 APPEAR_* 표를 만든다.

핵심: 남자와 여자가 **서로 다른 색의 옷**을 입고 있다. recolor 는 0행 하나만
표준으로 삼으므로, 0행에 **두 벌을 나란히** 담는다.
  슬롯 0~4 = 남자 옷 다섯 단, 슬롯 5~9 = 여자 옷 다섯 단
다른 행(선택지)은 두 묶음에 **같은 색**을 넣는다 — 어느 쪽 도트를 쓰든
고른 색으로 갈아입혀진다. 0행을 고르면 둘 다 그려진 그대로 남는다.

신발·살결은 남녀가 같은 색을 쓰므로 한 묶음이면 된다.
"""

def shades(base, style):
    """기본색에서 [기본, 그늘, 밝은 면, 깊은 그늘, 아주 밝은 면] 다섯 단.

    RGB 를 배수로 곱하면 따뜻한 색에서 색조가 튄다(흙빛 분홍이 형광 살구가
    됐다). 색상(H)은 그대로 두고 명도(V)와 채도(S)만 옮긴다 — 어두울수록
    채도를 올리고 밝을수록 내리는 게 팩 스웨터에서 잰 비율이다."""
    import colorsys
    h, s, v = colorsys.rgb_to_hsv(*[c / 255.0 for c in base])
    if style == 'cloth':      # 팩 스웨터 (89,133,159) 에서 잰 값
        k = ((1.00, 1.00), (0.77, 1.27), (1.17, 0.71), (0.55, 1.34), (1.31, 0.30))
    else:                     # 팩 머리 (146,112,98)
        k = ((1.00, 1.00), (0.77, 1.03), (1.23, 1.07), (0.51, 0.73), (1.40, 0.73))
    out = []
    for vf, sf in k:
        r, g, b = colorsys.hsv_to_rgb(h, min(1.0, s * sf), min(1.0, v * vf))
        out.append([int(round(r * 255)), int(round(g * 255)), int(round(b * 255))])
    return out


def pair(a, b=None):
    """0행은 남·여 두 벌, 다른 행은 같은 색 두 번."""
    return a + (b if b else a)


