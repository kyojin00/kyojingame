def face_hw(y):
    return FACE if y <= 21 else (5 if y == 22 else 4)


def head(top, side, bang=None, spike=(), hang=()):
    """머리 하나. 다섯 가지만 적으면 나온다 (맨 위 설명 참고)."""
    g = [['.'] * LW for _ in range(LH)]

    def put(y, a, b, c):
        for x in range(max(0, a), min(LW - 1, b) + 1):
            g[y][x] = c

    for y, span in enumerate(top):
        if span:
            put(y, span[0], span[1], 'h')
    for i, sp in enumerate(side):
        y = 12 + i
        fh = face_hw(y)
        put(y, CX - fh, CX + fh - 1, 'H')
        if sp:
            put(y, sp[0], CX - fh - 1, 'h')
            put(y, CX + fh, sp[1], 'h')
    for i, sp in enumerate(hang):          # 어깨 아래로 흘러내리는 머리.
        if sp:                             # 통으로 깔면 몸이 위에서 덮는다
            put(24 + i, sp[0], sp[1], 'h')
    for x, y in spike:
        g[y][x] = 'h'
    for x, n in (bang or {}).items():      # 앞머리를 칸마다 더 내린다
        for k in range(n):
            if g[12 + k][x] in ('H', '.'):
                g[12 + k][x] = 'h'
    for x in (12, 13, 18, 19):             # 눈 — 2칸 x 3줄
        for y in (17, 18, 19):
            g[y][x] = 'e'
    for x in (10, 11, 20, 21):             # 볼
        g[20][x] = 'r'
    g[21][15] = 'm'                        # 입은 한 칸이면 족하다
    return [''.join(r) for r in g]


