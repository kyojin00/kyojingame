class Grid:
    def __init__(self, head_rows, body):
        self.d = [list(r) for r in head_rows]
        for y, row in body.items():        # 몸이 머리 위에 온다
            for x, ch in enumerate(row):
                if ch != '.':
                    self.d[y][x] = ch

    def at(self, x, y):
        if 0 <= x < LW and 0 <= y < LH:
            c = self.d[y][x]
            return None if c == '.' else c
        return None

    def shade(self):
        """명암은 「덩어리 오른쪽 끝을 한 단 내린 것」이 전부다. 빛은 왼쪽 위.
        폭 두 칸을 무조건 내리면 폭 3칸짜리 팔이 통째로 어두워진다."""
        dark = {'H': 's', 's': 'S', 'b': 'B', 'p': 'P', 'k': 'n', 'h': 'g'}
        for row in self.d:
            x = 0
            while x < LW:
                c = row[x]
                if c not in dark:
                    x += 1
                    continue
                j = x
                while j < LW and row[j] == c:
                    j += 1
                n = 2 if j - x >= 8 else (1 if j - x >= 3 else 0)
                for k in range(j - n, j):
                    row[k] = dark[c]
                x = j

    def shine(self):
        """머리 윤기 — 정수리 왼쪽. **머리 모양을 따라** 놓아야 한다.
        네모로 칠하면 딱지를 붙인 것처럼 보인다."""
        for x in range(9, 16):
            hit = [y for y in range(LH) if self.at(x, y) in HAIR]
            if not hit:
                continue
            top = hit[0] + (2 if x < 12 else 1)
            for y in (top, top + 1):
                if self.at(x, y) in HAIR:
                    self.d[y][x] = 'j'

    def outline(self):
        add = []
        for y in range(LH):
            for x in range(LW):
                if self.at(x, y) is not None:
                    continue
                if any(self.at(x + dx, y + dy) not in (None, 'O')
                       for dx, dy in ((-1, 0), (1, 0), (0, -1), (0, 1))):
                    add.append((x, y))
        for x, y in add:
            self.d[y][x] = 'O'

    def save(self, path):
        im = Image.new('RGBA', (W, H), (0, 0, 0, 0))
        o = im.load()
        for y in range(LH):
            for x in range(LW):
                c = self.at(x, y)
                if not c:
                    continue
                col = PAL[c] + (255,)
                for dy in range(PXL):
                    for dx in range(PXL):
                        py = y * PXL + dy + YOFF
                        if 0 <= py < H:
                            o[x * PXL + dx, py] = col
        im.save(path)
        return im


def build(hair, body):
    g = Grid(head(**hair), body)
    g.shade()
    g.shine()
    g.outline()
    return g


