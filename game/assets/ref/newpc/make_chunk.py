# 몸통은 한 벌로 두고 **머리 모양만 갈아 끼운다**. 머리는
#   · top   : y0~11 줄마다 머리 반폭
#   · side  : y12~23 줄마다 옆머리 두께
#   · bang  : x 마다 앞머리를 몇 줄 더 내릴지 (일자로 자르면 바가지다)
#   · spike : 손으로 찍는 삐친 뭉치
#   · hang  : 어깨 아래로 내려오는 옆머리 (여자)
