# 참고 그림에서 뽑은 규칙 셋:
#   1. **면마다 색이 하나.** 그라데이션이 없다. 명암은 「덩어리 오른쪽 끝을
#      한 단 내린 것」이 전부다
#   2. **윤곽이 굵고 새까맣다.** 바깥 둘레뿐 아니라 팔과 몸통 사이, 두 다리
#      사이에도 들어간다. 형태를 읽게 하는 건 이 까만 줄이다
#   3. **머리가 키의 절반.** 그리고 머리카락이 얼굴보다 훨씬 넓어 얼굴을
#      액자처럼 감싼다 — 얼굴만 크면 밋밋한 살구색 판이 된다
#
# 몸통은 한 벌로 두고 **머리 모양만 갈아 끼운다**. 머리는
#   · top   : y0~11 줄마다 머리 반폭
#   · side  : y12~23 줄마다 옆머리 두께
#   · bang  : x 마다 앞머리를 몇 줄 더 내릴지 (일자로 자르면 바가지다)
#   · spike : 손으로 찍는 삐친 뭉치
#   · hang  : 어깨 아래로 내려오는 옆머리 (여자)
# 이 다섯 가지만 적으면 머리 하나가 나온다.
