def face_hw(y):
    return FACE if y <= 21 else (5 if y == 22 else 4)


def head(top, side, bang=None, spike=(), hang=()):
    """머리 하나. 다섯 가지만 적으면 나온다 (맨 위 설명 참고)."""
    g = [['.'] * LW for _ in range(LH)]

    def put(y, a, b, c):
        for x in range(max(0, a), min(LW - 1, b) + 1):
            g[y][x] = c

    for y, hw in enumerate(top):
        if hw:
            put(y, CX - hw, CX + hw - 1, 'h')
    for i, sw in enumerate(side):
        y = 12 + i
        fh = face_hw(y)
        put(y, CX - fh, CX + fh - 1, 'H')
        if sw:
            put(y, CX - fh - sw, CX - fh - 1, 'h')
            put(y, CX + fh, CX + fh + sw - 1, 'h')
    for i, sw in enumerate(hang):          # 어깨 아래로 흘러내리는 머리
        if sw:
            put(24 + i, 6 - sw, 5, 'h')
            put(24 + i, 26, 25 + sw, 'h')
    for x, y in spike:
        g[y][x] = 'h'
    for x, n in (bang or {}).items():      # 앞머리를 칸마다 더 내린다
        for k in range(n):
            if g[12 + k][x] in ('H', '.'):
                g[12 + k][x] = 'h'
    for x in (12, 13, 18, 19):             # 눈 — 2칸 x 3줄
        for y in (17, 18, 19):
            g[y][x] = 'e'
    for x in (10, 11, 20, 21):             # 볼
        g[20][x] = 'r'
    g[21][15] = 'm'                        # 입은 한 칸이면 족하다
    return [''.join(r) for r in g]


