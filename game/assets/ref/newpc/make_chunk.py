# 정반대다. 재 보니 **32 x 48 칸**이고, 규칙이 셋뿐이다:
#
#   1. **면마다 색이 하나.** 그라데이션이 없다. 살결 한 색, 머리 한 색,
#      옷 한 색. 명암은 「덩어리를 한 단 내린 것」이 전부다
#   2. **윤곽은 굵고 새까맣다.** 바깥 둘레뿐 아니라 팔과 몸통 사이,
#      두 다리 사이에도 까만 줄이 들어간다. 이게 형태를 읽게 한다
#   3. **머리가 크다.** 머리(머리카락 포함)가 키의 절반 가까이 된다
#
# 그래서 32 x 48 로 그리고 네 배로 키워 128 x 192 로 만든다. 정수배로
# 키우므로 칸이 정확히 4 x 4 로 떨어져 참고 그림처럼 각지게 나온다.
#
# 한 칸 한 칸을 글자로 적되, 「글자 몇 개」를 세어 적는다 — 32칸을 눈으로
# 세다 틀리면 그림이 어긋나므로 합이 32인지 기계가 확인하게 한다.
