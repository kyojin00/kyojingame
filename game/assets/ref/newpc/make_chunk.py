class Grid:
    def __init__(self, art):
        self.d = [list(r) for r in art]
        while len(self.d) < LH:
            self.d.append(list(E))

    def at(self, x, y):
        if 0 <= x < LW and 0 <= y < LH:
            c = self.d[y][x]
            return None if c == '.' else c
        return None

    def px(self, x, y, c):
        if 0 <= x < LW and 0 <= y < LH:
            self.d[y][x] = c

    def shade(self):
        """명암은 「덩어리를 한 단 내린 것」이 전부다. 빛은 왼쪽 위.

        오른쪽 두 칸을 한 단 어둡게, 머리 왼쪽 위 몇 칸을 한 단 밝게.
        참고 그림처럼 면마다 색이 하나여야 하므로 이 이상은 넣지 않는다."""
        dark = {'H': 's', 's': 'S', 'b': 'B', 'p': 'P', 'k': 'n', 'h': 'g'}
        for y in range(LH):
            row = self.d[y]
            # 그 줄에서 같은 재질이 이어지는 토막마다 오른쪽 끝 두 칸을 내린다
            x = 0
            while x < LW:
                c = row[x]
                if c not in dark:
                    x += 1
                    continue
                j = x
                while j < LW and row[j] == c:
                    j += 1
                n = 2 if j - x >= 8 else (1 if j - x >= 3 else 0)
                for k in range(j - n, j):
                    row[k] = dark[c]
                x = j

    def bangs(self, bang):
        """앞머리 끝을 칸마다 다르게 내린다 — 일자로 자르면 바가지다."""
        for x, n in bang.items():
            for y in range(LH):
                if self.at(x, y) in tuple(SKIN):
                    for k in range(n):
                        self.px(x, y + k, 'h')
                    break

    def shine(self):
        """머리 윤기 — 정수리 왼쪽, **머리 모양을 따라** 한 줄.
        네모로 칠하면 딱지를 붙인 것처럼 보인다."""
        for x in range(9, 16):
            hit = [y for y in range(LH) if self.at(x, y) in tuple(HAIR)]
            if not hit:
                continue
            top = hit[0] + (2 if x < 12 else 1)
            for y in (top, top + 1):
                if self.at(x, y) in tuple(HAIR):
                    self.px(x, y, 'j')

    def outline(self):
        add = []
        for y in range(LH):
            for x in range(LW):
                if self.at(x, y) is not None:
                    continue
                if any(self.at(x + dx, y + dy) not in (None, 'O')
                       for dx, dy in ((-1, 0), (1, 0), (0, -1), (0, 1))):
                    add.append((x, y))
        for x, y in add:
            self.px(x, y, 'O')

    def save(self, path):
        im = Image.new('RGBA', (W, H), (0, 0, 0, 0))
        o = im.load()
        for y in range(LH):
            for x in range(LW):
                c = self.at(x, y)
                if not c:
                    continue
                col = PAL[c] + (255,)
                for dy in range(PXL):
                    for dx in range(PXL):
                        py = y * PXL + dy + YOFF
                        if 0 <= py < H:
                            o[x * PXL + dx, py] = col
        im.save(path)
        return im


def build(art, bang):
    g = Grid(art)
    g.bangs(bang)
    g.shade()
    g.shine()
    g.outline()
    return g


