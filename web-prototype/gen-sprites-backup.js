// ---- 지형 타일 (웹 버전 색상 + 디테일을 텍스처로 굽기) ----
function hash(x, y) {
  let h = (x * 374761393 + y * 668265263) | 0;
  h = ((h ^ (h >> 13)) * 1274126177) | 0;
  h = h ^ (h >> 16);
  return (h >>> 0) / 4294967295;
}

